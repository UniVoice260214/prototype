def build_styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    styles: dict[str, ParagraphStyle] = {}
    styles["body"] = ParagraphStyle(
        "body", parent=base["Normal"], fontName=FONT_REGULAR,
        fontSize=10.5, leading=17, alignment=TA_JUSTIFY, spaceAfter=8,
    )
    styles["overview_h"] = ParagraphStyle(
        "overview_h", parent=base["Normal"], fontName=FONT_BOLD,
        fontSize=16, textColor=colors.HexColor("#0b3d5c"), spaceAfter=10,
    )
    styles["chapter_title"] = ParagraphStyle(
        "chapter_title", parent=base["Normal"], fontName=FONT_BOLD,
        fontSize=17, textColor=colors.HexColor("#0b3d5c"), leading=23,
        spaceAfter=12,
    )
    styles["section"] = ParagraphStyle(
        "section", parent=base["Normal"], fontName=FONT_BOLD,
        fontSize=12, textColor=colors.HexColor("#154360"), leading=16,
        spaceBefore=10, spaceAfter=4,
    )
    styles["title_main"] = ParagraphStyle(
        "title_main", parent=base["Normal"], fontName=FONT_BOLD, fontSize=28,
        alignment=TA_CENTER, textColor=colors.HexColor("#0b3d5c"), leading=36,
    )
    styles["title_sub"] = ParagraphStyle(
        "title_sub", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=13,
        alignment=TA_CENTER, textColor=colors.HexColor("#2471a3"), leading=20,
    )
    styles["title_foot"] = ParagraphStyle(
        "title_foot", parent=base["Normal"], fontName=FONT_REGULAR, fontSize=10.5,
        alignment=TA_CENTER, textColor=colors.HexColor("#555555"), leading=16,
    )
    return styles


def _header(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont(FONT_REGULAR, 8.5)
    canvas.setFillColor(colors.HexColor("#999999"))
    w, h = A4
    if doc.page > 1:
        canvas.drawString(2.3 * cm, h - 1.3 * cm, f"{DOC_TITLE} · {doc.page - 1}")
    canvas.restoreState()


def _blank(canvas, doc) -> None:
    pass


def p(text: str, style: ParagraphStyle) -> Paragraph:
    return Paragraph(escape(str(text)), style)


def build() -> None:
    register_fonts()
    st = build_styles()

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc = BaseDocTemplate(
        str(OUT_PATH), pagesize=A4,
        leftMargin=2.3 * cm, rightMargin=2.3 * cm,
        topMargin=2.4 * cm, bottomMargin=2.0 * cm,
        title=DOC_TITLE, author="UniVoice RAG Knowledge Builder",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")
    doc.addPageTemplates([PageTemplate(id="body", frames=[frame], onPage=_header)])

    story: list = [
        Spacer(1, 8 * cm),
        p(DOC_TITLE, st["title_main"]),
        Spacer(1, 0.5 * cm),
        p(DOC_SUBTITLE, st["title_sub"]),
        Spacer(1, 1.2 * cm),
        p(f"개념 관계·비교 중심의 RAG 지식 문서 · 전 {len(CHAPTERS)}장", st["title_foot"]),
        PageBreak(),
        p("개요", st["overview_h"]),
        p(OVERVIEW, st["body"]),
        PageBreak(),
    ]

    for i, ch in enumerate(CHAPTERS):
        story.append(p(f"{ch['num']}장. {ch['title']}", st["chapter_title"]))
        for sec in ch["sections"]:
            story.append(p(sec["title"], st["section"]))
            for para in sec["paras"]:
                story.append(p(para, st["body"]))
        if i < len(CHAPTERS) - 1:
            story.append(PageBreak())

    doc.build(story)
    print(f"생성 완료: {OUT_PATH}  ({len(CHAPTERS)}개 장)")


if __name__ == "__main__":
    build()
